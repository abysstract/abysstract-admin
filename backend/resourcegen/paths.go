package resourcegen

import (
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

const (
	goManifestName  = ".adminresource-go.manifest"
	tsManifestName  = ".adminresource-ts.manifest"
	generatedHeader = "// CODE GENERATED BY adminresource-gen. DO NOT EDIT."
)

func outputDir(root, relative string) string {
	return filepath.Join(root, filepath.FromSlash(relative))
}

func underRoot(root, target string) bool {
	rel, err := filepath.Rel(root, target)
	if err != nil {
		return false
	}
	if rel == "." {
		return true
	}
	if rel == ".." || strings.HasPrefix(rel, ".."+string(os.PathSeparator)) {
		return false
	}
	return true
}

func checkOutputLocation(fsys fileSystem, root, relative, kind string) (string, error) {
	abs := outputDir(root, relative)
	if !underRoot(root, abs) {
		return "", fmt.Errorf("resourcegen: %s output escapes RootDir", kind)
	}
	if err := walkExistingParents(fsys, root, abs); err != nil {
		return "", err
	}
	info, err := fsys.Lstat(abs)
	if err == nil {
		if info.Mode()&os.ModeSymlink != 0 {
			resolved, resolveErr := fsys.EvalSymlinks(abs)
			if resolveErr != nil {
				return "", fmt.Errorf("resourcegen: resolve %s output: %w", kind, resolveErr)
			}
			if !underRoot(root, resolved) {
				return "", fmt.Errorf("resourcegen: %s output symlink escapes RootDir", kind)
			}
			abs = resolved
		} else if !info.IsDir() {
			return "", fmt.Errorf("resourcegen: %s output is not a directory", kind)
		}
	} else if !os.IsNotExist(err) {
		return "", err
	}
	return abs, nil
}

func walkExistingParents(fsys fileSystem, root, target string) error {
	current := target
	for {
		if current == root {
			return nil
		}
		info, err := fsys.Lstat(current)
		if err != nil {
			if os.IsNotExist(err) {
				parent := filepath.Dir(current)
				if parent == current {
					return fmt.Errorf("resourcegen: output is not under RootDir")
				}
				current = parent
				continue
			}
			return err
		}
		if info.Mode()&os.ModeSymlink != 0 {
			resolved, resolveErr := fsys.EvalSymlinks(current)
			if resolveErr != nil {
				return fmt.Errorf("resourcegen: resolve parent %s: %w", current, resolveErr)
			}
			if !underRoot(root, resolved) {
				return fmt.Errorf("resourcegen: output parent symlink escapes RootDir")
			}
		}
		return nil
	}
}

func safeManagedName(name, suffix string) bool {
	return filepath.Base(name) == name &&
		!filepath.IsAbs(name) &&
		strings.HasSuffix(name, suffix) &&
		!strings.Contains(name, "..") &&
		!strings.Contains(name, string(os.PathSeparator)) &&
		!strings.Contains(name, "/")
}

func inspectExistingFile(fsys fileSystem, dir, name string) error {
	path := filepath.Join(dir, name)
	info, err := fsys.Lstat(path)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return fmt.Errorf("resourcegen: managed file %s is a symlink", name)
	}
	if info.IsDir() {
		return fmt.Errorf("resourcegen: managed path %s is a directory", name)
	}
	data, err := fsys.ReadFile(path)
	if err != nil {
		return err
	}
	content := string(data)
	if !strings.HasPrefix(content, generatedHeader+"\n") && !strings.HasPrefix(content, generatedHeader+"\r\n") {
		return fmt.Errorf("resourcegen: %s exists and is not a generated file", name)
	}
	return nil
}

func readManifest(fsys fileSystem, dir, kind string) ([]string, error) {
	manifestPath := filepath.Join(dir, ".adminresource-"+kind+".manifest")
	data, err := fsys.ReadFile(manifestPath)
	if err != nil {
		if os.IsNotExist(err) || isNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	var names []string
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		names = append(names, line)
	}
	return names, nil
}

func isNotExist(err error) bool {
	return os.IsNotExist(err) || err == fs.ErrNotExist
}

func manifestBytes(names []string) []byte {
	if len(names) == 0 {
		return []byte{}
	}
	return []byte(strings.Join(names, "\n") + "\n")
}

func TestRenderGoRepositoryUpdateNormalizesTimestamp(t *testing.T) {
	files, err := renderGo(widgetPlan(t))
	if err != nil {
		t.Fatalf("renderGo: %v", err)
	}
	var code string
	for _, f := range files {
		if strings.HasSuffix(f.name, "_repo.gen.go") {
			code = string(f.content)
			break
		}
	}
	if code == "" {
		t.Fatal("missing generated repo source")
	}
	if !strings.Contains(code, "resource.NormalizeTimestamp(time.Now())") {
		t.Fatalf("repo update source missing NormalizeTimestamp helper\n---\n%s", code)
	}
	if strings.Contains(code, ".Round(time.Microsecond)") {
		t.Fatalf("repo update source must not round PostgreSQL audit timestamps\n---\n%s", code)
	}
}

func TestGeneratedFilesHaveDoNotEditHeader(t *testing.T) {
	plan := divergentResourcePlan(t)
	goSource := renderGoConvSource(t, plan)
	_, tsSource, err := renderTS(plan)
	if err != nil {
		t.Fatal(err)
	}
	const header = "// CODE GENERATED BY adminresource-gen. DO NOT EDIT."
	if !strings.HasPrefix(string(goSource), header+"\n") {
		t.Fatal("generated Go file is missing the required first-line header")
	}
	if !strings.HasPrefix(string(tsSource), header+"\n") {
		t.Fatal("generated TS file is missing the required first-line header")
	}
}


func TestRenderGoUsesImmutableDBNameColumnSet(t *testing.T) {
	plan := divergentResourcePlan(t)
	field := plan.Field("DictLabel")
	if field == nil {
		t.Fatal("DictLabel field missing")
	}
	// Prove the template consumes the validated FieldPlan.DBName rather than
	// re-deriving a column from ProtoName/JSONName.
	field.DBName = "stored_label"

	src := renderGoConvSource(t, plan)
	code := string(src)

	checks := []string{
		`const DictDataColumnDictLabel resource.Column = "stored_label"`,
		`(*model.SysDictDatum, resource.ColumnSet, error)`,
		`var columns []resource.Column`,
		`columns = append(columns, DictDataColumnDictLabel)`,
		`resource.NewColumnSet(columns...)`,
	}
	for _, check := range checks {
		if !strings.Contains(code, check) {
			t.Errorf("generated converter missing %q\n---\n%s", check, code)
		}
	}
	if strings.Contains(code, "[]string") || strings.Contains(code, `append(columns, "dict_label")`) {
		t.Fatalf("generated converter must not expose raw string columns\n---\n%s", code)
	}
}


// Task 7.6: validation metadata lives in Schema. Rebuilding and rendering
// after a MaxLen change updates generated validation without touching Service.
func TestRenderGoTracksSchemaMaxLenDrift(t *testing.T) {
	resource := divergentResource(t)
	for i := range resource.Fields {
		if resource.Fields[i].Name == "DictLabel" {
			resource.Fields[i] = schema.F("DictLabel", schema.Required(), schema.MaxLen(200))
		}
	}
	plan, err := resource.Build()
	if err != nil {
		t.Fatal(err)
	}
	source := renderGoConvSource(t, plan)
	code := string(source)
	if !strings.Contains(code, "字段 dict_label 长度不能超过 200") {
		t.Fatalf("rendered validator did not adopt Schema MaxLen(200)\n---\n%s", code)
	}
	if strings.Contains(code, "字段 dict_label 长度不能超过 100") {
		t.Fatalf("rendered validator retained stale Schema MaxLen(100)\n---\n%s", code)
	}
}

// Hook instances are runtime dependencies of generated controllers. Converter
// rendering must never execute or embed Hook initialization code, otherwise the
// schema package would regain a bootstrap dependency on application services.
func TestRenderGoDoesNotInitializeHooks(t *testing.T) {
	source := renderGoConvSource(t, divergentResourcePlan(t))
	code := string(source)
	for _, forbidden := range []string{"HookSet[", "BeforeCreate:", "AfterCommitCreate:"} {
		if strings.Contains(code, forbidden) {
			t.Fatalf("generated converter must not initialize Hooks (%q found)\n---\n%s", forbidden, code)
		}
	}
}

// renderGoConvSource renders the converter source for tests that predate the
// multi-output renderGo (conv + optional repo adapter).
func renderGoConvSource(t *testing.T, p *schema.Plan) []byte {
	t.Helper()
	files, err := renderGo(p)
	if err != nil {
		t.Fatalf("renderGo: %v", err)
	}
	for _, f := range files {
		if strings.HasSuffix(f.name, "_conv.gen.go") {
			return f.content
		}
	}
	t.Fatalf("no conv output in %v", files)
	return nil
}


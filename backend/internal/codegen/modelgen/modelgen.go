// Package modelgen generates GORM models and queries for module tables.
package modelgen

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"

	"gorm.io/gorm"

	"github.com/abysstract/abysstract-admin/backend/internal/codegen/modelcfg"
	"github.com/abysstract/abysstract-admin/backend/internal/codegen/tableprefix"
)

// Module selects one module's tables and its model output directory.
type Module struct {
	Name        string `json:"name"`
	TablePrefix string `json:"tablePrefix"`
	ModelOutput string `json:"modelOutput"`
}

// Generate writes model/ and query/ below root/<ModelOutput> for every module.
// All modules are checked for overlapping table prefixes; only selected is
// generated when it is not empty.
func Generate(db *gorm.DB, driver, root string, modules []Module, selected string) error {
	var owners []tableprefix.Owner
	for _, module := range modules {
		if err := tableprefix.Validate(module.TablePrefix); err != nil {
			return fmt.Errorf("module %q: %w", module.Name, err)
		}
		owners = append(owners, tableprefix.Owner{Module: module.Name, Prefix: module.TablePrefix})
	}
	if err := tableprefix.CheckOverlap(owners); err != nil {
		return err
	}
	if selected != "" {
		found := false
		for i, module := range modules {
			if module.Name == selected {
				modules = modules[i : i+1]
				found = true
				break
			}
		}
		if !found {
			return fmt.Errorf("unknown module %q", selected)
		}
	}
	tables, err := db.Migrator().GetTables()
	if err != nil {
		return err
	}
	sort.Strings(tables)
	for _, module := range modules {
		if err := generateModule(db, driver, root, module, tables); err != nil {
			return err
		}
	}
	return nil
}

func generateModule(db *gorm.DB, driver, root string, module Module, tables []string) error {
	moduleTables := selectTables(tables, module.TablePrefix)
	if len(moduleTables) == 0 {
		return fmt.Errorf("module %q has no tables with prefix %q", module.Name, tableprefix.Normalize(module.TablePrefix))
	}
	output := filepath.Join(root, filepath.FromSlash(module.ModelOutput))
	// Inventory only GORM-owned files; handwritten files remain outside cleanup.
	previous := map[string]bool{}
	expected := map[string]bool{filepath.Join(output, "query", "gen.go"): true}
	for _, table := range moduleTables {
		expected[filepath.Join(output, "model", table+".gen.go")] = true
		expected[filepath.Join(output, "query", table+".gen.go")] = true
	}
	for _, dir := range []string{"model", "query"} {
		entries, err := os.ReadDir(filepath.Join(output, dir))
		if err != nil && !os.IsNotExist(err) {
			return err
		}
		for _, entry := range entries {
			if entry.IsDir() {
				continue
			}
			file := filepath.Join(output, dir, entry.Name())
			data, err := os.ReadFile(file)
			if err != nil {
				return err
			}
			owned := bytes.HasPrefix(data, []byte("// Code generated by gorm.io/gen."))
			if expected[file] && !owned {
				return fmt.Errorf("unmanaged destination: %s", file)
			}
			if owned {
				previous[file] = true
			}
		}
	}
	g := modelcfg.NewGenerator(db, output)
	for _, table := range moduleTables {
		opts, err := modelcfg.TableOptions(db, driver, table)
		if err != nil {
			return err
		}
		g.ApplyBasic(g.GenerateModel(table, opts...))
	}
	g.Execute()
	for file := range previous {
		if !expected[file] {
			if err := os.Remove(file); err != nil {
				return err
			}
		}
	}
	return nil
}

// selectTables picks a module's tables at the "<prefix>_" boundary.
func selectTables(tables []string, prefix string) []string {
	var selected []string
	for _, table := range tables {
		if tableprefix.Match(prefix, table) {
			selected = append(selected, table)
		}
	}
	return selected
}

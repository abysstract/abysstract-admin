const generatedHeader = "// Code generated by admin module sync. DO NOT EDIT.\n"

func goSource(src string) ([]byte, error) { return format.Source([]byte(generatedHeader + src)) }

// moduleImport is the Go import path of a module's backend package.
func (l appLayout) moduleImport(d descriptor) string {
	if d.builtin != "" {
		return d.builtin
	}
	return l.importPath(d.Backend.Package)
}

func render(root string, defs []descriptor) (map[string][]byte, error) {
	layout, err := loadLayout(root)
	if err != nil {
		return nil, err
	}
	out := map[string][]byte{}
	var backend, frontend strings.Builder
	backend.WriteString("package app\nimport (\n\"" + frameworkImport + "module\"\n")
	frontend.WriteString(generatedHeader)
	for i, d := range defs {
		fmt.Fprintf(&backend, "m%d %q\n", i, layout.moduleImport(d))
		relative := d.Frontend.Import
		if relative == "" {
			relative, err = relativeImport(layout.FrontendRoot, strings.TrimSuffix(d.Frontend.Entry, path.Ext(d.Frontend.Entry)))
			if err != nil {
				return nil, err
			}
		}
		fmt.Fprintf(&frontend, "import { %s as m%d } from %q;\n", d.Frontend.Export, i, relative)
	}
	taskSource, gen, protoPaths, err := renderGenerationTasks(root, layout, defs)
	if err != nil {
		return nil, err
	}
	backend.WriteString(")\nfunc selectedModules() ([]module.Definition, error) {\nvar defs []module.Definition\n")
	for i, d := range defs {
		fmt.Fprintf(&backend, "d%d, err := m%d.%s()\nif err != nil { return nil, err }; defs = append(defs, d%d)\n", i, i, d.Backend.Constructor, i)
	}
	backend.WriteString("return defs, nil\n}\n")
	frontend.WriteString("\n// prettier-ignore\nexport const modules = [\n")
	for i := range defs {
		fmt.Fprintf(&frontend, "  m%d,\n", i)
	}
	frontend.WriteString("];\n")

	// Empty import blocks are valid Go and gofmt preserves compilation.
	out["backend/internal/app/modules.gen.go"], err = goSource(backend.String())
	if err != nil {
		return nil, err
	}
	out[layout.FrontendRoot+"/modules.gen.ts"] = []byte(frontend.String())
	registry, err := renderMigrations(root, out)
	if err != nil {
		return nil, err
	}
	out["backend/migrations/go_registry.gen.go"] = registry
	if !layout.Framework {
		// The repository-wide generation inventory belongs to the framework;
		// an application generates one module at a time with module generate.
		return out, nil
	}
	out["backend/internal/codegen/resources/tasks.gen.go"] = taskSource
	// Preserve the existing generator consumer format; protoSource belongs to the descriptor.
	type task struct {
		Name        string `json:"name"`
		TablePrefix string `json:"tablePrefix"`
		ModelOutput string `json:"modelOutput"`
		Prefix      string `json:"prefix"`
		GoOutput    string `json:"goOutput"`
		TSOutput    string `json:"tsOutput"`
	}
	inventory := make([]task, 0, len(gen))
	for _, g := range gen {
		inventory = append(inventory, task{g.Name, g.TablePrefix, g.ModelOutput, g.Prefix, g.GoOutput, g.TSOutput})
	}
	out["backend/internal/codegen/modules.json"], err = jsonBytes(inventory)
	if err != nil {
		return nil, err
	}
	out["buf.yaml"], err = renderBufConfig(root, protoPaths)
	if err != nil {
		return nil, err
	}
	return out, nil
}

// migrationDrivers lists the dialects whose migration directory exists. An
// application keeps directories only for the databases it supports.
func migrationDrivers(root string) ([]string, error) {
	var drivers []string
	for _, driver := range []string{"postgres", "mysql", "mariadb", "sqlite"} {
		info, err := os.Stat(filepath.Join(root, "backend/migrations", driver))
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return nil, err
		}
		if info.IsDir() {
			drivers = append(drivers, driver)
		}
	}
	return drivers, nil
}

// renderMigrations scans historical factory declarations without importing application code.
func renderMigrations(root string, pending map[string][]byte) ([]byte, error) {
	layout, err := loadLayout(root)
	if err != nil {
		return nil, err
	}
	drivers, err := migrationDrivers(root)
	if err != nil {
		return nil, err
	}
	for path := range pending {
		dir := filepath.ToSlash(filepath.Dir(path))
		if driver, ok := strings.CutPrefix(dir, "backend/migrations/"); ok && strings.HasSuffix(path, ".go") && !slices.Contains(drivers, driver) {
			drivers = append(drivers, driver)
		}
	}
	factories := map[string][]string{}
	for _, driver := range drivers {
		dir := "backend/migrations/" + driver
		files, err := filepath.Glob(filepath.Join(root, dir, "*.go"))
		if err != nil {
			return nil, err
		}
		inputs := map[string][]byte{}
		for _, file := range files {
			if strings.HasSuffix(file, "_test.go") {
				continue
			}
			rel, err := filepath.Rel(root, file)
			if err != nil {
				return nil, err
			}
			data, err := os.ReadFile(file)
			if err != nil {
				return nil, err
			}
			inputs[filepath.ToSlash(rel)] = data
		}
		for path, data := range pending {
			if filepath.ToSlash(filepath.Dir(path)) == dir && strings.HasSuffix(path, ".go") {
				inputs[path] = data
			}
		}
		names := make([]string, 0, len(inputs))
		for name := range inputs {
			names = append(names, name)
		}
		sort.Strings(names)
		for _, name := range names {
			factory, err := migrationFactory(name, inputs[name])
			if err != nil {
				return nil, err
			}
			if factory != "" {
				factories[driver] = append(factories[driver], factory)
			}
		}
	}
	var src strings.Builder
	src.WriteString("package migrations\nimport (\n\"github.com/pressly/goose/v3\"\n")
	for _, driver := range drivers {
		if len(factories[driver]) > 0 {
			fmt.Fprintf(&src, "%s %q\n", driver, layout.importPath("backend/migrations/"+driver))
		}
	}
	src.WriteString(")\nfunc goMigrations(driver string) []*goose.Migration {\nswitch driver {\n")
	for _, driver := range drivers {
		fmt.Fprintf(&src, "case %q:\nreturn []*goose.Migration{\n", driver)
		for _, name := range factories[driver] {
			fmt.Fprintf(&src, "%s.%s(),\n", driver, name)
		}
		src.WriteString("}\n")
	}
	src.WriteString("}\npanic(\"unsupported migration driver: \" + driver)\n}\n")
	return goSource(src.String())
}

func writeFiles(root string, files map[string][]byte, check bool) ([]string, error) {
	paths := make([]string, 0, len(files))
	for p := range files {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	var changed []string
	for _, path := range paths {
		full, err := localPath(root, path)
		if err != nil {
			return nil, err
		}
		old, err := os.ReadFile(full)
		if err != nil && !os.IsNotExist(err) {
			return nil, err
		}
		if err == nil && bytes.Equal(old, files[path]) {
			continue
		}
		changed = append(changed, path)
	}
	if check {
		return changed, nil
	}
	for _, path := range changed {
		full := filepath.Join(root, path)
		if err := os.MkdirAll(filepath.Dir(full), 0755); err != nil {
			return changed, err
		}
		tmp, err := os.CreateTemp(filepath.Dir(full), ".admin-module-*")
		if err != nil {
			return changed, err
		}
		_, writeErr := tmp.Write(files[path])
		closeErr := tmp.Close()
		if writeErr != nil {
			return changed, errors.Join(writeErr, closeErr, os.Remove(tmp.Name()))
		}
		if closeErr != nil {
			return changed, errors.Join(closeErr, os.Remove(tmp.Name()))
		}
		if err := os.Chmod(tmp.Name(), 0644); err != nil {
			return changed, errors.Join(err, os.Remove(tmp.Name()))
		}
		if err := os.Rename(tmp.Name(), full); err != nil {
			return changed, errors.Join(err, os.Remove(tmp.Name()))
		}
	}
	return changed, nil
}

func renderBufConfig(root string, protoPaths []map[string]string) ([]byte, error) {
	base, err := os.ReadFile(filepath.Join(root, "buf.base.yaml"))
	if err != nil {
		return nil, err
	}
	var cfg map[string]any
	if err := yaml.UnmarshalStrict(base, &cfg); err != nil {
		return nil, err
	}
	cfg["modules"] = protoPaths
	data, err := yaml.Marshal(cfg)
	if err != nil {
		return nil, err
	}
	return append([]byte("# Code generated by admin module sync. DO NOT EDIT.\n"), data...), nil
}

func migrationFactory(name string, data []byte) (string, error) {
	file, err := parser.ParseFile(token.NewFileSet(), name, data, 0)
	if err != nil {
		return "", err
	}
	var found []string
	for _, decl := range file.Decls {
		f, ok := decl.(*ast.FuncDecl)
		if !ok || f.Recv != nil || !f.Name.IsExported() || f.Type.Params.NumFields() != 0 || f.Type.Results == nil || len(f.Type.Results.List) != 1 {
			continue
		}
		star, ok := f.Type.Results.List[0].Type.(*ast.StarExpr)
		if !ok {
			continue
		}
		sel, ok := star.X.(*ast.SelectorExpr)
		if !ok || sel.Sel.Name != "Migration" {
			continue
		}
		pkg, ok := sel.X.(*ast.Ident)
		if !ok || pkg.Name != "goose" {
			continue
		}
		found = append(found, f.Name.Name)
	}
	if len(found) == 0 && !versioned(filepath.Base(name)) {
		// Package documentation and helpers carry no migration version.
		return "", nil
	}
	if len(found) != 1 {
		return "", fmt.Errorf("%s: expected one exported goose migration factory, got %d", name, len(found))
	}
	return found[0], nil
}

// versioned reports a goose file name that starts with a 14-digit version.
func versioned(name string) bool {
	stamp, _, ok := strings.Cut(name, "_")
	if !ok || len(stamp) != 14 {
		return false
	}
	for _, r := range stamp {
		if r < '0' || r > '9' {
			return false
		}
	}
	return true
}

func renderGenerationTasks(root string, layout appLayout, defs []descriptor) ([]byte, []generation, []map[string]string, error) {
	var tasks strings.Builder
	tasks.WriteString("package resources\nimport (\n")
	var gen []generation
	var protoPaths []map[string]string
	for i, d := range defs {
		if d.Resource != nil {
			fmt.Fprintf(&tasks, "r%d %q\n", i, layout.importPath(d.Resource.Package))
		}
		if d.Generation != nil {
			gen = append(gen, *d.Generation)
			hasProto := false
			if err := filepath.WalkDir(filepath.Join(root, d.Generation.ProtoSource), func(path string, entry os.DirEntry, err error) error {
				if err != nil {
					return err
				}
				if !entry.IsDir() && strings.HasSuffix(path, ".proto") {
					hasProto = true
				}
				return nil
			}); err != nil {
				return nil, nil, nil, err
			}
			if hasProto {
				protoPaths = append(protoPaths, map[string]string{"path": d.Generation.ProtoSource})
			}
		}
	}
	tasks.WriteString(")\nfunc Tasks(root string) []Task {\nreturn []Task{\n")
	for i, d := range defs {
		if d.Resource != nil {
			fmt.Fprintf(&tasks, "{Name: %q, Config: r%d.%s(root), Resources: r%d.%s()},\n", d.Name, i, d.Resource.Config, i, d.Resource.Resources)
		}
	}
	tasks.WriteString("}\n}\n")
	source, err := goSource(tasks.String())
	return source, gen, protoPaths, err
}

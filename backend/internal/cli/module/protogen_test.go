func TestHasGeneratedMarker(t *testing.T) {
	cases := []struct {
		name string
		data string
		want bool
	}{
		{"go first line", "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n", true},
		{"es first line", "// @generated by protoc-gen-es v2.2.0\nimport x from \"y\";\n", true},
		{"after leading proto comment", "// My service\n// spans two lines\n\n// Code generated by protoc-gen-go. DO NOT EDIT.\n// versions:\npackage x\n", true},
		{"es after leading comment", "// Card edit service.\n\n// @generated by protoc-gen-es v2.2.0 with parameter \"target=ts\"\n/* eslint-disable */\n", true},
		{"hand written", "// Package x does things.\npackage x\n", false},
		{"marker after code", "package x\n\n// Code generated by protoc-gen-go. DO NOT EDIT.\n", false},
		{"empty", "", false},
	}
	for _, tc := range cases {
		if got := hasGeneratedMarker([]byte(tc.data)); got != tc.want {
			t.Errorf("%s: got %v, want %v", tc.name, got, tc.want)
		}
	}
}

func TestCheckManagedAcceptsLeadingComment(t *testing.T) {
	dest := t.TempDir()
	file := "company/shop/v1/foo.pb.go"
	path := filepath.Join(dest, filepath.FromSlash(file))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	header := "// My service\n\n// Code generated by protoc-gen-go. DO NOT EDIT.\npackage shopv1\n"
	if err := os.WriteFile(path, []byte(header), 0o644); err != nil {
		t.Fatal(err)
	}
	output := map[string][]byte{file: []byte(header)}
	if err := checkManaged(dest, "company/shop/", output); err != nil {
		t.Fatalf("checkManaged: %v", err)
	}
	if err := os.WriteFile(path, []byte("// hand written\npackage shopv1\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := checkManaged(dest, "company/shop/", output); err == nil || !strings.Contains(err.Error(), "unmanaged destination") {
		t.Fatalf("want unmanaged destination, got %v", err)
	}
}

import { execFileSync } from "node:child_process";
import {
  mkdtempSync,
  readFileSync,
  readdirSync,
  mkdirSync,
  writeFileSync,
  rmSync,
  existsSync,
} from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { rewriteProtoImports } from "./rewrite-proto-imports.mjs";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const args = process.argv.slice(2);
let inventory = path.join(root, "backend/internal/codegen/modules.json");
let config = path.join(root, "buf.yaml");
for (let i = 0; i < args.length; i += 2) {
  if (!args[i + 1]) throw new Error(`missing value for ${args[i]}`);
  if (args[i] === "--inventory") inventory = args[i + 1];
  else if (args[i] === "--config") config = args[i + 1];
  else throw new Error(`unknown argument ${args[i]}`);
}
const tasks = JSON.parse(readFileSync(inventory, "utf8"));
const temp = mkdtempSync(path.join(tmpdir(), "admin-proto-"));
function files(dir, prefix = "") {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? files(path.join(dir, e.name), prefix + e.name + "/") : [prefix + e.name],
  );
}
const destinations = [];
try {
  let template = readFileSync(path.join(root, "proto/buf.gen.yaml"), "utf8");
  const overrides = tasks
    .map(
      (task) => `    - file_option: go_package_prefix
      path: ${task.prefix.slice(0, -1)}
      value: github.com/abysstract/abysstract-admin/${task.goOutput}
`,
    )
    .join("");
  template = template.replace("plugins:", overrides + "plugins:");
  let index = 0;
  template = template.replace(
    /^ {4}out: .*$/gm,
    () => `    out: ${path.join(temp, index++ < 2 ? "go" : "ts")}`,
  );
  execFileSync("buf", ["generate", "--config", config, "--template", template], { cwd: root, stdio: "inherit" });
  const allGoFiles = files(path.join(temp, "go"));
  const allTSFiles = files(path.join(temp, "ts"));
  const moduleFiles = new Map(
    tasks.flatMap((task) =>
      allTSFiles
        .filter((file) => file.startsWith(task.prefix))
        .map((file) => [file, path.join(root, task.tsOutput, file)]),
    ),
  );
  const systemFiles = new Set(allTSFiles.filter((file) => file.startsWith("abysstract/")));

  if (
    [...allGoFiles, ...allTSFiles].some(
      (file) => !tasks.some((task) => file.startsWith(task.prefix)),
    )
  )
    throw new Error("unexpected generated output inventory");
  for (const task of tasks) {
    const prefix = task.prefix;
    const goFiles = allGoFiles.filter((file) => file.startsWith(prefix));
    const tsFiles = allTSFiles.filter((file) => file.startsWith(prefix));
    if (!goFiles.length && !tsFiles.length) {
      if (
        files(path.join(root, task.goOutput, prefix)).length ||
        files(path.join(root, task.tsOutput, prefix)).length
      )
        throw new Error(`module ${task.name} has generated protocol files but no protocol sources`);
      continue;
    }
    if (!goFiles.length || !tsFiles.length)
      throw new Error("unexpected generated output inventory");
    const rewritten = rewriteProtoImports(
      new Map(tsFiles.map((f) => [f, readFileSync(path.join(temp, "ts", f), "utf8")])),
      systemFiles,
      moduleFiles,
      path.join(root, task.tsOutput),
    );
    destinations.push(
      [
        path.join(root, task.goOutput),
        new Map(goFiles.map((f) => [f, readFileSync(path.join(temp, "go", f), "utf8")])),
        prefix,
      ],
      [path.join(root, task.tsOutput), rewritten, prefix],
    );
  }
  // Validate every managed destination before updating any formal output.
  for (const [dest, output, prefix] of destinations) {
    for (const f of new Set([
      ...files(path.join(dest, prefix)).map((f) => prefix + f),
      ...output.keys(),
    ])) {
      const full = path.join(dest, f);
      if (
        existsSync(full) &&
        !/^\/\/ (Code generated by |@generated by )/.test(readFileSync(full, "utf8"))
      )
        throw new Error(`unmanaged destination: ${full}`);
    }
  }
  for (const [dest, output, prefix] of destinations) {
    for (const [f, text] of output) {
      const full = path.join(dest, f);
      mkdirSync(path.dirname(full), { recursive: true });
      writeFileSync(full, text);
    }
    for (const f of files(path.join(dest, prefix)).map((f) => prefix + f))
      if (!output.has(f)) rmSync(path.join(dest, f));
  }
} finally {
  rmSync(temp, { recursive: true, force: true });
}

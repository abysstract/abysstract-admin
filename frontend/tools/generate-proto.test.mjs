import { test } from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import {
  mkdtempSync,
  mkdirSync,
  writeFileSync,
  readFileSync,
  cpSync,
  symlinkSync,
  rmSync,
  existsSync,
} from "node:fs";
import path from "node:path";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";
const tools = path.dirname(fileURLToPath(import.meta.url));
const modules = readFileSync(
  path.resolve(tools, "../../backend/internal/codegen/modules.json"),
  "utf8",
);
for (const mode of ["unknown-import", "handwritten", "valid"]) {
  test(`generation destination preflight: ${mode}`, () => {
    const root = mkdtempSync(path.join(tmpdir(), "admin-proto-preflight-"));
    const write = (name, text) => {
      mkdirSync(path.dirname(path.join(root, name)), { recursive: true });
      writeFileSync(path.join(root, name), text);
    };
    try {
      cpSync(tools, path.join(root, "frontend/tools"), { recursive: true });
      symlinkSync(
        path.resolve(tools, "../node_modules"),
        path.join(root, "frontend/node_modules"),
        "dir",
      );
      write(
        "proto/buf.gen.yaml",
        "plugins:\n  - remote: go\n    out: go\n  - remote: connect\n    out: go\n  - remote: es\n    out: ts\n",
      );
      write(
        "backend/internal/codegen/modules.json",
        JSON.stringify([
          {
            prefix: "abysstract/admin/v1/",
            goOutput: "backend/gen",
            tsOutput: "frontend/packages/admin-proto/src",
          },
          {
            name: "drafts",
            prefix: "company/drafts/v1/",
            goOutput: "backend/internal/modules/drafts/gen/proto",
            tsOutput: "frontend/apps/reference/src/modules/drafts/gen/proto",
          },
        ]),
      );
      const go = "backend/gen/abysstract/admin/v1/common.pb.go";
      const ts = "frontend/packages/admin-proto/src/abysstract/admin/v1/common_pb.ts";
      write(go, "// Code generated by fixture\nold go");
      write(ts, mode === "handwritten" ? "// hand-authored\n" : "// @generated by fixture\nold ts");
      const before = [
        readFileSync(path.join(root, go), "utf8"),
        readFileSync(path.join(root, ts), "utf8"),
      ];
      write(
        "bin/buf",
        `#!${process.execPath}\nif(process.argv[2] === 'lint') process.exit(0); const fs=require('node:fs'),p=require('node:path'); const template=process.argv[process.argv.indexOf('--template')+1]; const outputs=[...template.matchAll(/out: (.*)/g)].map(m=>m[1]); for(const [dir,file,text] of [[outputs[0],'common.pb.go','// Code generated by fixture\\nnew go'],[outputs[2],'common_pb.ts',${JSON.stringify(mode === "unknown-import" ? "// @generated by fixture\nexport {x} from './unknown_pb';" : "// @generated by fixture\nnew ts")}]]) {const out=p.join(dir,'abysstract/admin/v1',file); fs.mkdirSync(p.dirname(out),{recursive:true});fs.writeFileSync(out,text);}`,
      );
      execFileSync("chmod", ["+x", path.join(root, "bin/buf")]);
      let error;
      try {
        execFileSync(process.execPath, [path.join(root, "frontend/tools/generate-proto.mjs")], {
          cwd: tmpdir(),
          env: {
            ...process.env,
            PATH: path.join(root, "bin") + path.delimiter + process.env.PATH,
          },
          stdio: "pipe",
        });
      } catch (e) {
        error = e;
      }
      if (mode === "valid") {
        assert.equal(error, undefined);
        assert.equal(existsSync(path.join(root, "backend/internal/modules/drafts/gen/proto")), false);
        assert.match(readFileSync(path.join(root, go), "utf8"), /new go/);
        assert.match(readFileSync(path.join(root, ts), "utf8"), /new ts/);
      } else {
        assert.ok(error);
        assert.match(
          error.stderr.toString(),
          mode === "handwritten" ? /unmanaged destination/ : /unknown relative Proto dependency/,
        );
        assert.deepEqual(
          [readFileSync(path.join(root, go), "utf8"), readFileSync(path.join(root, ts), "utf8")],
          before,
        );
      }
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });
}

{
  test("business generation stays in the root application", () => {
    const base = mkdtempSync(path.join(tmpdir(), "admin-business-generation-"));
    const root = path.join(base, "project");
    const write = (name, text) => {
      mkdirSync(path.dirname(name), { recursive: true });
      writeFileSync(name, text);
    };
    try {
      cpSync(tools, path.join(root, "frontend/tools"), { recursive: true });
      symlinkSync(
        path.resolve(tools, "../node_modules"),
        path.join(root, "frontend/node_modules"),
        "dir",
      );
      write(path.join(root, "backend/internal/codegen/modules.json"), modules);
      write(path.join(root, "proto/abysstract/admin/v1/common.proto"), 'syntax = "proto3";');
      write(
        path.join(root, "proto/buf.gen.yaml"),
        "plugins:\n  - remote: go\n    out: go\n  - remote: connect\n    out: go\n  - remote: es\n    out: ts\n",
      );
      write(
        path.join(root, "backend/internal/modules/product/proto/company/product/v1/product.proto"),
        'syntax = "proto3";',
      );
      write(
        path.join(base, "bin/buf"),
        `#!${process.execPath}
const fs = require('node:fs'), p = require('node:path'), assert = require('node:assert/strict');
assert.ok(fs.existsSync('proto/abysstract/admin/v1/common.proto'));
assert.ok(fs.existsSync('backend/internal/modules/product/proto/company/product/v1/product.proto'));
if (process.argv[2] === 'generate') {
  assert.ok(!process.argv.includes('--path'));
  const prefixes = ['abysstract/admin/v1', 'company/product/v1'];
  const template = process.argv[process.argv.indexOf('--template') + 1];
  const outputs = [...template.matchAll(/out: (.*)/g)].map(m => m[1]);
  for (const prefix of prefixes) {
    for (const [dir, file, text] of [[outputs[0], 'product.pb.go', '// Code generated by fixture'], [outputs[2], 'product_pb.ts', '// @generated by fixture']]) {
      const out = p.join(dir, prefix, file);
      fs.mkdirSync(p.dirname(out), {recursive: true}); fs.writeFileSync(out, text);
    }
  }
}
`,
      );
      execFileSync("chmod", ["+x", path.join(base, "bin/buf")]);
      execFileSync(process.execPath, [path.join(root, "frontend/tools/generate-proto.mjs")], {
        cwd: tmpdir(),
        env: { ...process.env, PATH: path.join(base, "bin") + path.delimiter + process.env.PATH },
        stdio: "pipe",
      });
      assert.match(
        readFileSync(
          path.join(
            root,
            "backend/internal/modules/product/gen/proto/company/product/v1/product.pb.go",
          ),
          "utf8",
        ),
        /fixture/,
      );
      assert.match(
        readFileSync(
          path.join(
            root,
            "frontend/apps/reference/src/modules/product/gen/proto/company/product/v1/product_pb.ts",
          ),
          "utf8",
        ),
        /fixture/,
      );
      assert.equal(existsSync(path.join(root, "frontend/packages/admin-proto/src/company")), false);
      const systemGo = path.join(root, "backend/gen/abysstract/admin/v1/product.pb.go");
      const preserved = "// Code generated by fixture\nunchanged system";
      write(systemGo, preserved);
      write(
        path.join(
          root,
          "frontend/apps/reference/src/modules/product/gen/proto/company/product/v1/product_pb.ts",
        ),
        "// handwritten business file",
      );
      assert.throws(
        () =>
          execFileSync(process.execPath, [path.join(root, "frontend/tools/generate-proto.mjs")], {
            cwd: tmpdir(),
            env: {
              ...process.env,
              PATH: path.join(base, "bin") + path.delimiter + process.env.PATH,
            },
            stdio: "pipe",
          }),
        /Command failed/,
      );
      assert.equal(readFileSync(systemGo, "utf8"), preserved);
    } finally {
      rmSync(base, { recursive: true, force: true });
    }
  });
}
